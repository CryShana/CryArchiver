/// `tag` as its ISO 639-2/T code, lowercased and without a region (`en-US` is `eng`). A tag this doesn't know is
/// only lowercased and stripped of its region.
pub fn normalized(tag: &str) -> String {
	let primary = tag.split(['-', '_']).next().unwrap_or(tag).to_ascii_lowercase();
	TWO_LETTER
		.iter()
		.chain(BIBLIOGRAPHIC)
		.find(|(code, _)| *code == primary)
		.map_or(primary, |(_, terminology)| (*terminology).to_owned())
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn codes_that_mean_one_language_become_one_code() {
		assert_eq!(normalized("en"), "eng");
		assert_eq!(normalized("eng"), "eng");
		assert_eq!(normalized("en-US"), "eng");
		assert_eq!(normalized("GER"), "deu");
		assert_eq!(normalized("de"), "deu");
		assert_eq!(normalized("jpn"), "jpn");
		assert_eq!(normalized("und"), "und");
		assert_eq!(normalized("tlh"), "tlh");
	}

	#[test]
	fn the_tables_are_consistent() {
		assert!(TWO_LETTER.iter().all(|(two, three)| two.len() == 2 && three.len() == 3));
		assert!(
			BIBLIOGRAPHIC
				.iter()
				.all(|(_, terminology)| TWO_LETTER.iter().any(|(_, three)| three == terminology))
		);
	}
}
